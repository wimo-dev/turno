// Troubleshooting: one page per doctor finding
// ---------------------------------------------------------------------------------------------
{
  const findings = doctorFindings(ROOT).filter((f) => f.problem);
  const problems = [];
  const used = new Set();
  const pages = [];
  for (const f of findings) {
    const matches = DOCTOR_CHECKS.filter((c) => c.source === f.file && f.text.includes(c.match));
    if (matches.length !== 1) {
      problems.push(`${f.file}:${f.line} "${f.text}" matches ${matches.length} entries${matches.length ? ` (${matches.map((c) => c.id).join(", ")})` : ""}`);
      continue;
    }
    const entry = matches[0];
    if (used.has(entry.id)) problems.push(`${entry.id} matches more than one finding (second: ${f.file}:${f.line})`);
    used.add(entry.id);
    if (!entry.skip) pages.push({ ...entry, finding: f });
  }
  for (const c of DOCTOR_CHECKS) if (!used.has(c.id)) problems.push(`${c.id} ("${c.match}") matches no finding in ${c.source}`);
  const ids = DOCTOR_CHECKS.map((c) => c.id);
  for (const id of new Set(ids.filter((x, i) => ids.indexOf(x) !== i))) problems.push(`duplicate id ${id}`);
  if (problems.length) {
    throw new Error(`reference/doctor-checks.mjs is out of step with the doctor sources:\n  ${problems.join("\n  ")}\nGive every warning and failure exactly one entry (id, source, match, title, why).`);
  }

  const ICON = { warn: "!", fail: "x" };
  const levelWords = (levels) => {
    const l = levels.filter((x) => x === "warn" || x === "fail").map((x) => (x === "warn" ? "a warning" : "a failure"));
    return l.join(" or ");
  };
  const order = DOCTOR_SOURCES.map((s) => s.command).filter((c, i, a) => a.indexOf(c) === i);
  const sidebar = ["index"];
  const indexRows = [];
  for (const command of order) {
    sidebar.push(`---${command}---`);
    // Catalog order, so related checks sit together.
    const group = DOCTOR_CHECKS.map((c) => pages.find((p) => p.id === c.id)).filter((p) => p && p.finding.command === command);
    for (const p of group) {
      const f = p.finding;
      const fixFlag = `${command}${command === "turno browser doctor" ? "" : ""} --fix`;
      const icon = ICON[f.levels.includes("fail") ? "fail" : "warn"];
      const shown = [`  ${icon}  ${f.text}`];
      if (f.fix) shown.push(`     fix: ${f.fix}${f.fix === fixFlag ? "" : ` (${fixFlag} runs it)`}`);
      else if (f.hint) shown.push(`     fix: ${f.hint}`);
      else if (f.manual) shown.push(`     manual: ${f.manual}`);
      const fixLines = [];
      if (f.fix) {
        fixLines.push("Run:", "", fence(f.fix, "sh"), "", f.fix === fixFlag ? "This is one of the repairs that flag runs." : `\`${fixFlag}\` runs this repair for you, together with every other one it can.`);
      } else if (f.hint) {
        fixLines.push("Run:", "", fence(f.hint, "sh"), "", `\`${fixFlag}\` does not run it for you, because it needs a decision or an answer from you.`);
      } else if (f.manual) {
        fixLines.push(`${esc(sentence(f.manual))}`, "", "No single command fixes this one, so doctor names the manual step.");
      }
      if (p.fix) fixLines.push(fixLines.length ? "" : "", esc(p.fix));
      if (!fixLines.length) throw new Error(`${p.id}: the code names no fix; add "fix" to its entry in reference/doctor-checks.mjs`);
      const body = [
        `This page is for when \`${command}\` reports the finding below: what it means and how to fix it.`,
        "",
        "## What you see",
        "",
        fence(shown.join("\n")),
        "",
        `It is ${levelWords(f.levels)}${f.levels.includes("fail") ? `; a failure makes \`${command}\` exit with code 1` : "; warnings do not change the exit code"}.${/<[^>]+>/.test(shown.join("\n")) ? " Words in angle brackets stand for values from your machine." : ""}`,
        "",
        "## Why it happens",
        "",
        esc(p.why).replace(/`([^`]*)`/g, (_, c) => `\`${c.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&#123;/g, "{").replace(/&#125;/g, "}").replace(/&amp;/g, "&")}\``),
        "",
        "## Fix",
        "",
        ...fixLines,
        "",
        `Then run \`${command}\` again to see the row turn into \`ok\`.`,
        "",
        `The check lives in [\`${f.file}\`](${REPO}/blob/main/${f.file}).`,
      ];
      emit(`troubleshooting/${p.id}.mdx`, page({ title: p.title, description: `What ${command} means by "${f.text.length > 80 ? `${f.text.slice(0, 77)}...` : f.text}", and the fix.`, body: body.join("\n") }));
      sidebar.push(p.id);
      indexRows.push({ command, row: [`[${esc(p.title)}](/docs/troubleshooting/${p.id})`, code(f.text), f.levels.includes("fail") ? (f.levels.includes("warn") ? "warning or failure" : "failure") : "warning"] });
    }
  }
  // The filter comes before the sample run: a reader who arrives with a symptom types it first.
  const intro = [
    "This page is for when something does not work: run `turno doctor`, find the row it flags, and open its page here.",
    "",
    "```sh",
    "turno doctor                  # every check, with the fix under each problem",
    "turno doctor --fix            # run every repair that is safe to run, then check again",
    "turno doctor --security       # file modes, the port owner, literal secrets, unpinned servers, token age, the audit log",
    "turno doctor --summary        # one line, for hooks and status lines",
    "turno doctor --report         # a Markdown block for an issue: versions, agents, paths, mcpd, findings",
    "turno browser doctor          # Chrome and every browser identity (needs turno-browser)",
    "```",
    "",
    "It exits with code 1 when a check fails; warnings exit 0. Each row below is one finding, with what doctor prints for it.",
    "",
    // The rows stay plain Markdown tables (llms.txt and the Markdown copy read them as they are);
    // components/docs/finding-filter.tsx only hides the ones that do not match.
    "<FindingFilter>",
    "",
  ];
  for (const command of order) {
    intro.push(`## ${command}`, "", table(["Finding", "What doctor prints", "Level"], indexRows.filter((r) => r.command === command).map((r) => r.row)), "");
  }
  intro.push("</FindingFilter>", "");
  intro.push(
    "## What a run looks like",
    "",
    "`turno doctor` checks the system, your config files, every profile, the MCP servers, the look and the gateway. Under each problem it prints the command that fixes it (`fix:`) or the manual step (`manual:`). This is a run in a fresh HOME, before any setup (`-` rows are skipped checks, with an optional next step):",
    "",
    fence(DOCTOR_SAMPLE, "text", 'title="turno doctor"'),
    "",
  );
  intro.push(
    "## When doctor finds nothing",
    "",
    "```sh",
    "turno mcp daemon status       # running servers, clients, memory; or why mcpd is down",
    "turno mcp daemon logs -n 100  # the gateway log, in local time",
    "turno mcp log --server <name> # its recent tool calls, with errors and durations",
    "turno mcp refresh <name>      # forget a cached tool list; a running mcpd relearns it",
    "turno mcp call <name> [tool]  # list a server's tools, or call one, as a profile's session would",
    "turno run <profile> --no-gateway  # the same account without the gateway or the status line",
    "```",
    "",
    "If a problem goes away with `--no-gateway` (or `TURNO_SAFE=1`), it comes from turno's gateway or status line; if it stays, from the agent or its account.",
    "",
    `Each server also has its own stderr log under \`~/.local/state/turno/logs/\`. If you are still stuck, ask in [Discussions](${REPO}/discussions) or open an [issue](${REPO}/issues) with the output of \`turno doctor --report\`, which holds no tokens or secret values.`,
  );
  emit("troubleshooting/index.mdx", page({ title: "Troubleshooting", description: "Run turno doctor, then find the row it flags: one page per finding, with its fix.", body: intro.join("\n") }));
  // A root folder, like reference: its own sidebar, grouped by the command that reports each finding.
  meta("troubleshooting/meta.json", { title: "Troubleshooting", description: "One page per doctor finding", root: true, pages: sidebar });
}

