// Write or check
// ---------------------------------------------------------------------------------------------
const check = process.argv.includes("--check");
const stale = [];
const walk = (dir) => {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else {
      const rel = relative(CONTENT, full);
      if (files.has(rel)) continue;
      // meta.json files and marked pages are ours; anything else is hand-written.
      if (name === "meta.json" || readFileSync(full, "utf8").includes(MARKER)) stale.push(rel);
    }
  }
};
for (const dir of OWNED) walk(join(CONTENT, dir));
// reference/index.mdx is hand-written; its meta.json is generated.
const changed = [];
for (const [rel, content] of files) {
  const full = join(CONTENT, rel);
  const current = existsSync(full) ? readFileSync(full, "utf8") : undefined;
  if (current === content) continue;
  changed.push(rel);
  if (!check) {
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
}
if (!check) for (const rel of stale) rmSync(join(CONTENT, rel));
if (check && (changed.length || stale.length)) {
  console.error("The generated docs are out of date with the code. Run: pnpm build && pnpm docs:generate");
  for (const f of changed) console.error(`  changed  apps/docs/content/docs/${f}`);
  for (const f of stale) console.error(`  stale    apps/docs/content/docs/${f}`);
  process.exit(1);
}
console.log(check ? `generated docs are up to date (${files.size} files)` : `wrote ${changed.length} of ${files.size} files${stale.length ? `, removed ${stale.length} stale` : ""}`);
