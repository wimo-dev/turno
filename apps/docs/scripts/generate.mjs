#!/usr/bin/env node
// Writes the reference and troubleshooting pages from the code, so they cannot drift:
//
//   node scripts/generate.mjs           write the pages under content/docs
//   node scripts/generate.mjs --check   fail when a page on disk differs from what the code says
//
// Sources (build the packages first: pnpm build at the repository root):
//   - commands and their help: the command registry (dist/cli/registry.js) and `turno <command>
//     --help`, run in a throwaway HOME so nothing of this machine is read or shown;
//   - config.toml keys: `turno config --help` and KNOWN_KEYS in core/config.ts;
//   - mcp.toml keys: the annotated block in docs/mcp.md, checked against the keys the parser
//     in core/manifest.ts reads;
//   - environment variables, exit codes, JSON output: `turno help <topic>` and cli/exit.ts;
//   - troubleshooting: every warning and failure in the doctor sources
//     (scripts/lib/doctor-findings.mjs), named by reference/doctor-checks.mjs.
