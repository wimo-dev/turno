// ---------------------------------------------------------------------------------------------
// Running the CLI: a throwaway HOME, a fixed width, no colors, no update check.
// ---------------------------------------------------------------------------------------------
const home = mkdtempSync(join(tmpdir(), "turno-docs-"));
process.on("exit", () => rmSync(home, { recursive: true, force: true }));

function turno(...args) {
  const res = spawnSync(process.execPath, [ENTRY, ...args], {
    encoding: "utf8",
    cwd: home,
    env: { HOME: home, PATH: "/usr/bin:/bin", TURNO_NO_UPDATE_CHECK: "1", NO_COLOR: "1", COLUMNS: "100", TERM: "dumb", LANG: "en_US.UTF-8" },
  });
  if (res.status !== 0) throw new Error(`turno ${args.join(" ")} exited ${res.status}: ${res.stderr}`);
  const text = res.stdout
    .split("\n")
    .map((l) => l.trimEnd())
    .join("\n")
    .trim();
  if (text.includes(home)) throw new Error(`turno ${args.join(" ")} printed the throwaway HOME; its output would differ between machines`);
  return text;
}

// ---------------------------------------------------------------------------------------------
// MDX helpers
// ---------------------------------------------------------------------------------------------
/** Text that goes into prose or a table cell: no JSX, no expressions, no column breaks. */
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;").replace(/\|/g, "\\|");
/** Inline code inside a table cell or prose. */
const code = (s) => `\`${s.replace(/\|/g, "\\|")}\``;
const fence = (text, lang = "text", meta = "") => {
  const ticks = text.includes("```") ? "````" : "```";
  return `${ticks}${lang}${meta ? ` ${meta}` : ""}\n${text}\n${ticks}`;
};
const page = ({ title, description, body }) => `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${MARKER}\n\n${body.trim()}\n`;
const table = (head, rows) => [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const sentence = (s) => `${s.charAt(0).toUpperCase()}${s.slice(1)}${/[.!?)]$/.test(s) ? "" : "."}`;

/** Rows of a `columns()` block in help text: `  left   right`, with wrapped lines under `right`. */
function parseColumns(lines) {
  const rows = [];
  for (const line of lines) {
    if (!line.trim()) continue;
    const m = /^ {2}(\S.*?) {2,}(\S.*)$/.exec(line);
    if (m) rows.push([m[1], m[2]]);
    else if (/^ {2}\S/.test(line)) rows.push([line.trim(), ""]);
    else if (rows.length) rows.at(-1)[1] = `${rows.at(-1)[1]} ${line.trim()}`.trim();
  }
  return rows;
}

